// End-to-end test for the dynamic skill-loading pipeline introduced by
// `injectedSkills` going from `Set<string>` → `Map<name, fingerprint>` and
// the proactive `hotReloadCurrentTab` call in `editSkillTool` /
// `createSkillTool`.
//
// The test runs in two phases on a single headed chromium with the
// extension loaded:
//
//   Phase A — mechanical pipeline (no agent involved):
//     1. Navigate to example.com.
//     2. Drive `sw:edit_skill` directly from the service worker context
//        with a tiny skill that matches the current URL.
//     3. Push the updated active set into the tab via `cs:set_active_skills`
//        (this is what the storage watcher would do).
//     4. Verify `window.xgoose.skills.<ns>.<fn>` is callable in the page
//        MAIN world and returns the expected value — proves the
//        fingerprint cache lets a brand-new skill land mid-session.
//     5. Edit the skill body and repeat — proves the fingerprint cache
//        actually busts on `updatedAt` change (the regression we shipped
//        this fixes).
//
//   Phase B — agent flow:
//     1. Open the panel, send a prompt asking the agent to create a
//        small skill and then call it.
//     2. Verify the assistant's reply contains the value the new skill
//        returns — proves the agent's `create_skill` → `js_exec` loop
//        works end-to-end with the new hot-reload hint.
//
// Run with:
//   GEMINI_API_KEY=… node scripts/e2e-dynamic-skill.mjs

import { chromium } from 'playwright';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';

const __dirname = dirname(fileURLToPath(import.meta.url));
const distDir = resolve(__dirname, '..', 'dist');

const apiKey =
  process.env.GEMINI_API_KEY ||
  process.env.GEMINI_API ||
  process.env.XGOOSE_SECRET_GEMINI_API_KEY ||
  '';
if (!apiKey) {
  console.error('[e2e-dyn] no GEMINI_API_KEY / GEMINI_API set; aborting.');
  process.exit(2);
}

const TARGET_URL = 'https://example.com/';

// Tiny skill source for phase A. Self-contained: no `import` lines beyond
// the canonical pair (the SW bundler strips both). Returns a fixed string
// so we can assert exact equality. `defineSkill` takes the function spec
// map directly (each key becomes a callable on the namespace) — no
// `functions:` wrapper. The header carries the name/namespace/etc.
function buildSkillSource({ namespace, returnText }) {
  return `// ==XGooseSkill==
// @name        e2e-dyn-${namespace}
// @namespace   ${namespace}
// @version     1.0.0
// @description e2e dynamic-load probe — auto-generated by e2e-dynamic-skill.mjs
// @match       https://example.com/*
// @primary     echo
// ==/XGooseSkill==

import { defineSkill, fn } from '@xgoose/skill';
import { z } from 'zod';

export default defineSkill({
  echo: fn({
    summary: 'Return a fixed string so the harness can assert.',
    input: z.object({}),
    output: z.string(),
    examples: [],
    handler: () => ${JSON.stringify(returnText)},
  }),
});
`;
}

const userDataDir = mkdtempSync(`${tmpdir()}/xgoose-extension-chrome-e2e-dyn-`);

const ctx = await chromium.launchPersistentContext(userDataDir, {
  headless: false,
  args: [
    `--disable-extensions-except=${distDir}`,
    `--load-extension=${distDir}`,
    '--no-first-run',
    '--no-default-browser-check',
  ],
});

let exitCode = 0;
const results = [];

try {
  const sw = await waitForServiceWorker(ctx, 15_000);
  if (!sw) throw new Error('service worker never registered');
  log('boot', 'service worker UP');

  const extensionId = await sw.evaluate(() => chrome.runtime.id);
  log('boot', `extension id: ${extensionId}`);

  // Privileged bridge: a chrome-extension://<id>/options.html tab. Its
  // page.evaluate has full chrome.* access AND messages sent from it
  // ARE delivered to the SW's onMessage listener (unlike the SW sending
  // messages to itself, which is the MV3 limitation that broke phase A).
  const bridgePage = await ctx.newPage();
  await bridgePage.goto(`chrome-extension://${extensionId}/options.html`, {
    waitUntil: 'domcontentloaded',
  });

  // Diagnostic: confirm chrome.userScripts is available. If not, we fall
  // back to the new-Function path which is CSP-sensitive.
  const userScriptsAvail = await sw.evaluate(
    () =>
      typeof chrome.userScripts !== 'undefined' &&
      typeof chrome.userScripts.execute === 'function',
  );
  log('boot', `chrome.userScripts.execute available: ${userScriptsAvail}`);

  await seedSettings(ctx, {
    provider: 'gemini',
    apiKey,
    model: 'gemini-2.5-flash',
    baseUrl: '',
    thinking: false,
    theme: 'dark',
    jsExecTimeoutMs: 30000,
    redactSensitiveHeaders: true,
    redactSensitiveHeaderKeys: ['authorization', 'x-csrf-token', 'x-xsrf-token', 'x-api-key'],
  });
  log('boot', 'settings seeded (gemini-2.5-flash, thinking=false)');

  // ── Phase A: mechanical pipeline ─────────────────────────────────────
  results.push(await phaseA(ctx, sw, bridgePage));

  // ── Phase B: agent flow ─────────────────────────────────────────────
  results.push(await phaseB(ctx, sw, bridgePage));
} catch (err) {
  exitCode = 1;
  console.error('[e2e-dyn] fatal:', err);
} finally {
  console.log('\n========== SUMMARY ==========');
  for (const r of results) {
    const tag = r.ok ? 'PASS' : 'FAIL';
    console.log(`[${tag}] ${r.name}: ${r.notes || ''}`);
    if (!r.ok) exitCode = 1;
  }
  console.log('=============================\n');
  await ctx.close().catch(() => {});
  rmSync(userDataDir, { recursive: true, force: true });
  process.exit(exitCode);
}

async function phaseA(ctx, sw, bridgePage) {
  const tag = 'phaseA';
  log(tag, '─ MECHANICAL PIPELINE ─');
  const page = await ctx.newPage();
  const consoleLines = [];
  page.on('pageerror', (err) => consoleLines.push(`pageerror: ${err.message}`));
  page.on('console', (msg) => {
    const t = `${msg.type()}: ${msg.text()}`;
    if (t.includes('xgoose') || msg.type() === 'error' || msg.type() === 'warning') {
      consoleLines.push(t);
    }
  });

  try {
    log(tag, `navigating to ${TARGET_URL}`);
    await page.goto(TARGET_URL, { waitUntil: 'domcontentloaded', timeout: 30_000 });
    await page.waitForSelector('div#xgoose-root', { timeout: 15_000, state: 'attached' });
    await page.waitForTimeout(1000);

    // Step 1: create the skill via sw:edit_skill (this is what the agent's
    // `create_skill` tool does under the hood). The SW saves + bundles.
    const ns = 'e2edyn1';
    const src1 = buildSkillSource({ namespace: ns, returnText: 'hello-from-v1' });
    const editRes = await bridgeSend(bridgePage, 'sw:edit_skill', {
      name: 'e2e-dyn-e2edyn1',
      source: src1,
    });
    if (!editRes || editRes.ok !== true) {
      return fail(tag, page, `sw:edit_skill failed: ${JSON.stringify(editRes)}`);
    }
    log(tag, `sw:edit_skill ok (bodyChanged=${editRes.bodyChanged})`);

    // Step 2: trigger the same flow the storage watcher uses — fetch the
    // active set, then push to the tab. This is what `chrome.storage.onChanged`
    // → `sendToTab("cs:set_active_skills")` does in background/index.ts.
    const activeNames = await pushActiveSkillsToTab(sw, page, bridgePage);
    if (!activeNames.includes('e2e-dyn-e2edyn1')) {
      return fail(
        tag,
        page,
        `expected e2e-dyn-e2edyn1 in active set; got [${activeNames.join(',')}]`,
      );
    }
    log(tag, `active skills now: [${activeNames.join(', ')}]`);

    // Step 3: verify the IIFE actually mounted xgoose.skills.<ns>.echo on
    // the page MAIN world.
    const v1 = await runInPageMain(page, `return await window.xgoose.skills.${ns}.echo({});`);
    if (v1.error) {
      // Dump page-MAIN diagnostic state for debugging.
      const diag = await runInPageMain(
        page,
        `return { hasXgoose: typeof window.xgoose, hasSkills: typeof (window.xgoose && window.xgoose.skills), nsKeys: Object.keys(window.xgoose && window.xgoose.skills || {}), runtimeMounted: typeof window.__xgooseSkillRuntime };`,
      );
      return fail(
        tag,
        page,
        `phase-A v1 run failed: ${v1.error}; diag=${JSON.stringify(diag.result || diag.error)}; console=${JSON.stringify(consoleLines.slice(-10))}`,
      );
    }
    if (v1.result !== 'hello-from-v1') {
      return fail(tag, page, `phase-A v1 expected "hello-from-v1", got ${JSON.stringify(v1.result)}`);
    }
    log(tag, `v1 echo returned: ${JSON.stringify(v1.result)} ✓`);

    // Step 4: edit the skill (same name, new body) and repeat. This is the
    // regression we shipped this for: under the old Set<string> cache, the
    // re-inject would no-op and v2 would still return "hello-from-v1".
    const src2 = buildSkillSource({ namespace: ns, returnText: 'hello-from-v2' });
    const editRes2 = await bridgeSend(bridgePage, 'sw:edit_skill', {
      name: 'e2e-dyn-e2edyn1',
      source: src2,
    });
    if (!editRes2 || editRes2.ok !== true) {
      return fail(tag, page, `phase-A v2 sw:edit_skill failed: ${JSON.stringify(editRes2)}`);
    }
    log(tag, `v2 sw:edit_skill ok (bodyChanged=${editRes2.bodyChanged})`);

    await pushActiveSkillsToTab(sw, page, bridgePage);
    await page.waitForTimeout(300);

    const v2 = await runInPageMain(page, `return await window.xgoose.skills.${ns}.echo({});`);
    if (v2.error) return fail(tag, page, `phase-A v2 run failed: ${v2.error}`);
    if (v2.result !== 'hello-from-v2') {
      return fail(
        tag,
        page,
        `phase-A v2 expected "hello-from-v2", got ${JSON.stringify(v2.result)} — fingerprint cache may not be busting on updatedAt change!`,
      );
    }
    log(tag, `v2 echo returned: ${JSON.stringify(v2.result)} ✓ (fingerprint busted correctly)`);

    return {
      name: 'phaseA',
      ok: true,
      notes: `v1/v2 hot-reload via storage watcher works`,
    };
  } catch (err) {
    return fail(tag, page, `exception: ${err && err.message ? err.message : err}`);
  } finally {
    await page.close().catch(() => {});
    await bridgeSend(bridgePage, 'sw:delete_user_skill', { name: 'e2e-dyn-e2edyn1' }).catch(
      () => {},
    );
  }
}

async function phaseB(ctx, sw, bridgePage) {
  const tag = 'phaseB';
  log(tag, '─ AGENT FLOW (create_skill + js_exec) ─');
  const page = await ctx.newPage();
  const errors = [];
  page.on('pageerror', (err) => errors.push(`pageerror: ${err.message}`));
  page.on('console', (msg) => {
    if (msg.type() === 'error') errors.push(`console.error: ${msg.text()}`);
  });

  try {
    log(tag, `navigating to ${TARGET_URL}`);
    await page.goto(TARGET_URL, { waitUntil: 'domcontentloaded', timeout: 30_000 });
    await page.waitForSelector('div#xgoose-root', { timeout: 15_000, state: 'attached' });
    await page.waitForTimeout(1500);

    const prompt = [
      'You are running on https://example.com — verify with page_info first if you want.',
      '',
      'Now exercise the dynamic-skill flow:',
      '',
      "1. Call create_skill with this exact source (it's a tiny probe skill):",
      '',
      '```',
      buildSkillSource({ namespace: 'e2eAgent', returnText: 'agent-pong-42' }),
      '```',
      '',
      "   The skill's @name is `e2e-dyn-e2eAgent`. After create_skill returns, it should report `activeOnThisPage: true`.",
      '',
      "2. Invoke the skill's echo function via js_exec, exactly: `return await window.xgoose.skills.e2eAgent.echo({});`",
      '',
      "3. Reply with ONLY the return value as a single line, nothing else. No prose, no markdown, just the string.",
    ].join('\n');

    log(tag, 'opening panel + sending prompt (up to 120s for the agent loop)');
    const reply = await sendPromptAndWaitForReply(page, prompt, 120_000);
    log(tag, `agent reply: ${JSON.stringify((reply || '').slice(0, 200))}`);

    if (!reply) return fail(tag, page, 'agent never replied');
    const ok = /agent-pong-42/.test(reply);
    if (!ok) {
      // Pull the tool-call history off the panel for diagnosis.
      const toolCalls = await page.evaluate(() => {
        const root = document.querySelector('div#xgoose-root')?.shadowRoot;
        if (!root) return [];
        return Array.from(root.querySelectorAll('.tool-call, .msg-tool, .tool-name')).map((n) =>
          (n.textContent || '').trim().slice(0, 120),
        );
      });
      return fail(
        tag,
        page,
        `agent reply missing "agent-pong-42". reply=${JSON.stringify(reply.slice(0, 300))} toolCalls=${JSON.stringify(toolCalls.slice(0, 10))}`,
      );
    }
    return {
      name: 'phaseB',
      ok: true,
      notes: `agent created+invoked dynamically-loaded skill, errors=${errors.length}`,
    };
  } catch (err) {
    return fail(tag, page, `exception: ${err && err.message ? err.message : err}`);
  } finally {
    await page.close().catch(() => {});
    await bridgeSend(bridgePage, 'sw:delete_user_skill', { name: 'e2e-dyn-e2eAgent' }).catch(
      () => {},
    );
  }
}

// ── helpers ────────────────────────────────────────────────────────────

function fail(tag, page, msg) {
  log(tag, `FAIL: ${msg}`);
  return { name: tag, ok: false, notes: msg };
}

async function bridgeSend(bridgePage, kind, payload) {
  return await bridgePage.evaluate(
    async ({ kind, payload }) => {
      return await chrome.runtime.sendMessage({ kind, payload });
    },
    { kind, payload },
  );
}

async function pushActiveSkillsToTab(sw, page, bridgePage) {
  // Mirror what `background/index.ts` storage watcher does: fetch active
  // set for the tab's URL, then push via cs:set_active_skills.
  const url = page.url();
  const skills = await bridgeSend(bridgePage, 'sw:active_skills_for_url', { url });
  // Find the tab id of `page`. SW can enumerate tabs directly.
  const tabId = await sw.evaluate(async (targetUrl) => {
    const tabs = await chrome.tabs.query({});
    const t = tabs.find((t) => t.url === targetUrl);
    return t ? t.id : null;
  }, url);
  if (!tabId) throw new Error('could not find tab id for ' + url);
  await sw.evaluate(
    async ({ tabId, skills }) => {
      await chrome.tabs.sendMessage(tabId, {
        kind: 'cs:set_active_skills',
        payload: { skills },
      });
    },
    { tabId, skills },
  );
  // Give the content-script handler a moment to finish injectSkills.
  await page.waitForTimeout(1200);
  return (skills || []).map((s) => s.name);
}

// Run a snippet in the page MAIN world via the page-controller bridge.
// We can't just `page.evaluate` because that runs in the isolated world,
// where `window.xgoose` is undefined.
async function runInPageMain(page, code) {
  // Inject a one-shot script tag that posts the result back via a custom
  // event. Skips the bridge — keeps the harness self-contained.
  return await page.evaluate(async (snippet) => {
    return await new Promise((resolve) => {
      const eventName = '__xgoose_e2e_main_' + Math.random().toString(36).slice(2);
      window.addEventListener(eventName, (e) => resolve(e.detail), { once: true });
      const s = document.createElement('script');
      s.textContent =
        '(async () => {' +
        '  try {' +
        '    const result = await (async () => { ' +
        snippet +
        ' })();' +
        '    window.dispatchEvent(new CustomEvent(' + JSON.stringify(eventName) + ', { detail: { result } }));' +
        '  } catch (err) {' +
        '    window.dispatchEvent(new CustomEvent(' + JSON.stringify(eventName) + ', { detail: { error: String(err && err.message || err) } }));' +
        '  }' +
        '})();';
      (document.head || document.documentElement).appendChild(s);
      s.remove();
      setTimeout(() => resolve({ error: 'main-world snippet timed out' }), 8000);
    });
  }, code);
}

async function waitForServiceWorker(ctx, timeoutMs) {
  const deadline = Date.now() + timeoutMs;
  let sw = ctx.serviceWorkers()[0];
  while (!sw && Date.now() < deadline) {
    sw = await Promise.race([
      ctx.waitForEvent('serviceworker', { timeout: 500 }).catch(() => null),
      new Promise((r) => setTimeout(() => r(null), 500)),
    ]);
    if (!sw) sw = ctx.serviceWorkers()[0];
  }
  return sw;
}

async function seedSettings(ctx, settings) {
  const sw = ctx.serviceWorkers()[0];
  if (!sw) throw new Error('no service worker to seed settings');
  await sw.evaluate(async (s) => {
    await chrome.storage.local.set({ 'xgoose.settings': s });
  }, settings);
}

async function sendPromptAndWaitForReply(page, prompt, timeoutMs) {
  return await page.evaluate(
    async ({ prompt, timeoutMs }) => {
      const host = document.querySelector('div#xgoose-root');
      const root = host && host.shadowRoot;
      if (!root) return null;
      function waitFor(predicate, deadlineMs) {
        const deadline = Date.now() + deadlineMs;
        return new Promise((resolve) => {
          const tick = () => {
            const v = predicate();
            if (v) return resolve(v);
            if (Date.now() > deadline) return resolve(null);
            requestAnimationFrame(tick);
          };
          tick();
        });
      }
      const toggle = root.querySelector('.toggle');
      toggle && toggle.click();

      const ta = await waitFor(() => root.querySelector('.in-text'), 3000);
      const sendBtn = root.querySelector('.btn-send');
      if (!ta || !sendBtn) return null;
      ta.value = prompt;
      ta.dispatchEvent(new Event('input', { bubbles: true }));
      sendBtn.click();

      const knownBubblesAtStart = root.querySelectorAll('.msg-ai').length;
      return await waitFor(() => {
        const bubbles = root.querySelectorAll('.msg-ai');
        if (bubbles.length <= knownBubblesAtStart) return null;
        const bubble = bubbles[bubbles.length - 1];
        const t = bubble && bubble.textContent ? bubble.textContent.trim() : '';
        if (!t.length) return null;
        return t;
      }, timeoutMs);
    },
    { prompt, timeoutMs },
  );
}

function log(tag, msg) {
  // eslint-disable-next-line no-console
  console.log(`[e2e-dyn:${tag}] ${msg}`);
}
