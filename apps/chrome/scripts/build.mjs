// esbuild orchestration for the xgoose-extension-chrome MV3 extension.
//
// Outputs (all under dist/, which is what you `Load unpacked` into Chrome):
//   - background.js  (MV3 service worker, ESM)
//   - content.js     (isolated-world orchestrator)
//   - pageBridge.js  (MAIN-world bridge, re-exported from @xgoose/page-controller)
//   - popup.js       (settings popup)
//   - popup.html / popup.css  (static copies)
//   - manifest.json  (static copy)
//
// Pass `--watch` for incremental rebuilds while developing.

import { build, context } from 'esbuild';
import { rmSync, mkdirSync, cpSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');
const out = resolve(root, 'dist');
const isWatch = process.argv.includes('--watch');

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const entries = [
  { in: 'src/background/index.ts', out: 'background', format: 'esm' },
  { in: 'src/content/index.ts', out: 'content', format: 'iife' },
  { in: 'src/page/pageBridgeEntry.ts', out: 'pageBridge', format: 'iife' },
  { in: 'src/page/skillRuntimeEntry.ts', out: 'skillRuntime', format: 'iife' },
  { in: 'src/popup/index.ts', out: 'popup', format: 'iife' },
  { in: 'src/options/index.ts', out: 'options', format: 'iife' },
  { in: 'src/installPage/index.ts', out: 'installPage', format: 'iife' },
  { in: 'src/content/installer/installBanner.ts', out: 'installBanner', format: 'iife' },
];

const commonOpts = {
  bundle: true,
  platform: 'browser',
  target: ['chrome138'],
  // External `.map` rather than inline so the loaded JS is smaller; Chrome
  // DevTools still picks them up via the `sourceMappingURL` comment.
  sourcemap: 'linked',
  legalComments: 'none',
  logLevel: 'info',
};

async function run() {
  for (const e of entries) {
    const opts = {
      ...commonOpts,
      entryPoints: [resolve(root, e.in)],
      outfile: resolve(out, `${e.out}.js`),
      format: e.format,
    };
    if (isWatch) {
      const ctx = await context(opts);
      await ctx.watch();
    } else {
      await build(opts);
    }
  }
  copyStatics();
  // Emit the built-in skills (dist/skills/registry.json + *.xgs.js) as part of
  // the same build. This MUST run after the JS build because we `rmSync(out)`
  // the whole dist above — if the skill step ran first (or separately, like the
  // old `dev`/`build:js` paths), this wipe would delete dist/skills and leave
  // the extension with zero built-in skills (only user-installed ones survive).
  buildSkills();
  if (isWatch) {
    console.log('[xgoose-extension-chrome] watching for changes…');
  } else {
    console.log('[xgoose-extension-chrome] build done →', out);
  }
}

function buildSkills() {
  const script = resolve(__dirname, 'build-skills.mjs');
  try {
    execFileSync(process.execPath, [script], { stdio: 'inherit' });
  } catch (err) {
    // In watch mode a skill build failure shouldn't kill the JS watcher; surface
    // it and keep going. In a one-shot build, fail loudly.
    if (isWatch) {
      console.warn(
        '[xgoose-extension-chrome] skill build failed (continuing watch):',
        err?.message ?? err,
      );
    } else {
      throw err;
    }
  }
}

function copyStatics() {
  const staticDir = resolve(root, 'static');
  if (existsSync(staticDir)) {
    for (const name of [
      'manifest.json',
      'popup.html',
      'popup.css',
      'options.html',
      'options.css',
      'install.html',
      'install.css',
    ]) {
      const src = resolve(staticDir, name);
      if (existsSync(src)) cpSync(src, resolve(out, name));
    }
    // Toolbar / store icons. Generated by
    // xgoose-web/scripts/generate_extension_icons.py.
    const imagesDir = resolve(staticDir, 'images');
    if (existsSync(imagesDir)) {
      cpSync(imagesDir, resolve(out, 'images'), { recursive: true });
    }
  }
}

run().catch((err) => {
  console.error(err);
  process.exit(1);
});
